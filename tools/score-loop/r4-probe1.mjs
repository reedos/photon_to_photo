import { chromium } from 'playwright';
import { createServer } from 'vite';
const server = await createServer({ root: process.cwd(), logLevel: 'error', server: { host: '127.0.0.1', port: 0, open: false, watch: null, hmr: false } });
await server.listen();
const url = `http://127.0.0.1:${server.httpServer.address().port}`;
const browser = await chromium.launch({ channel: 'chrome', headless: true, args: ['--use-angle=d3d11', '--enable-unsafe-webgpu', '--ignore-gpu-blocklist'] });
const page = await browser.newPage({ viewport: { width: 1366, height: 900 }, reducedMotion: 'no-preference' });
page.setDefaultTimeout(120000);
await page.goto(`${url}/?piece=lens&lens=m50`);
await page.waitForFunction(() => window.p2p?.pieces.lens);
await page.waitForLoadState('networkidle');
await page.waitForFunction(() => !window.p2p.framing().moving);
await page.setViewportSize({ width: 390, height: 844 });
await page.locator('#view').scrollIntoViewIfNeeded();
await page.evaluate(() => window.p2p.piece('loupe'));
await page.waitForFunction(() => window.p2p.pieces.loupe.state().hasPixel && !window.p2p.pieces.loupe.state().pendingPixel);
await page.waitForFunction(() => !window.p2p.framing().moving);
await page.evaluate(() => window.p2p.piece('camera'));
const r = await page.evaluate(async () => {
  const v = () => { const e = document.querySelector('canvas'); return [e.clientWidth, e.clientHeight, document.getElementById('view').clientHeight]; };
  const out = {};
  out.stats0 = window.p2p.drawStats(); out.before = { view: v(), cam: window.p2p.pieces.lens.camera() };
  window.p2p.piece('lens');
  out.after = { view: v(), frame: window.p2p.framing(), cam: window.p2p.pieces.lens.camera() };
  await new Promise(r => setTimeout(r, 1500));
  out.stats = [window.p2p.drawStats()]; out.later = { view: v(), frame: window.p2p.framing(), cam: window.p2p.pieces.lens.camera() };
  return out;
});
console.log(JSON.stringify(r, (k, v) => typeof v === 'number' ? Math.round(v * 100) / 100 : v));
await browser.close(); await server.close();
